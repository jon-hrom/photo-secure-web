/**
 * Распознавание намерений в голосовом диалоге.
 *
 * Агент и клиент говорят свободно, поэтому команды ловим по ключевым фразам,
 * а не по точному совпадению: «создавай заявку», «оформляйте запись», «давай,
 * записывай» — всё это одна и та же команда «сохранить заявку в базу».
 */

/** Клиент (или агент) просит создать заявку прямо сейчас. */
const SUBMIT_PATTERNS: RegExp[] = [
  // «создавай/оформляй/записывай/подтверждай заявку (бронь, запись)»
  /(созда|оформ|запиш|записыв|заведи|заводи|сохран|отправ)\w*\s+(мне\s+|нам\s+|пожалуйста\s+)?(заявк|заяку|бронь|брониров|запис|клиент)/i,
  // «заявку создавай», «заявку оформляй» — обратный порядок слов
  /(заявк|бронь|запис)\w*\s+(созда|оформ|запиш|сохран|отправ)\w+/i,
  // короткое подтверждение без объекта: «да, создавай», «оформляй»
  /^(да[,!.\s]+)?(создавай|создай|создайте|оформляй|оформи|оформите|записывай|запиши|запишите|подтверждаю)[.!]?$/i,
];

/** Агент попрощался — разговор окончен, держать сессию незачем. */
const FAREWELL_PATTERNS: RegExp[] = [
  /хорошего\s+(дня|вечера|настроения)/i,
  /доброго\s+(дня|вечера|времени\s+суток)/i,
  /удачного\s+дня/i,
  /всего\s+(доброго|хорошего|наилучшего)/i,
  /до\s+(свидания|свидание|встречи|скорого)/i,
  /хорошей\s+съ[её]мки/i,
];

export function isSubmitIntent(text: string): boolean {
  const t = (text || '').trim();
  if (!t) return false;
  return SUBMIT_PATTERNS.some((re) => re.test(t));
}

export function isFarewell(text: string): boolean {
  const t = (text || '').trim();
  if (!t) return false;
  return FAREWELL_PATTERNS.some((re) => re.test(t));
}

export default { isSubmitIntent, isFarewell };
